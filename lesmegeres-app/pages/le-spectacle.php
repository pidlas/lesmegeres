      <h2 class="display-title">Comment on joue ?</h2>
      <p>
        Dans un premier temps, les comédien·e·s jouent une scène sans interruption. Puis, la scène est rejouée une 
        seconde fois. À n’importe quel moment une personne du public peut lever la main, la scène est mise sur pause 
        et lae spectateur·ice est alors invité·e à venir remplacer ou ajouter un personnage. Une fois sur scène, lae 
        <em>spectAct·eurice</em> devra tenter d’agir, de proposer des solutions concrètes afin de déjouer le problème 
        initial. La scène est rejouée plusieurs fois afin de permettre à plusieurs personnes du public d’expérimenter 
        leurs idées. Un·e médiateurice appelé·e lae joker, gère le bon déroulement de la séance. Iel favorise le débat, 
        analyse avec le public les interventions proposées et leurs répercussions sur la situation. Iel emmène la 
        réflexion collective le plus loin possible. Ensemble, comédien·ne·s, médiateurice et spectAct·eurice·s 
        cherchent et expérimentent sur scène différentes issues possibles à une situation de conflits. La question 
        présente dans la tête de chaque spectateurice·s est : “Qu’est ce que je peux faire pour que cela change ?”
      </p>
      <h2 class="display-title">C’est quoi la différence avec le théâtre tout court ?</h2>
